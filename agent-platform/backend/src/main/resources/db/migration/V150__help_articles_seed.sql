# 个人记忆：流水账、标签、总结、文件记忆

> 记忆系统会记住你在聊天里说过的事实（住哪、家人叫什么、项目进展），下次相关问题时 AI 自动想起来再回答。
> 统一入口：聊天页右上角「**记忆**」按钮 → 打开记忆抽屉。

## 一、记忆抽屉的 9 个页签

| 页签 | 干什么用 | 谁能用 |
|---|---|---|
| 流水账 | 每轮对话的原始记录（你说了什么、AI 答了什么） | 本人 |
| 标签库 | 查看/新建记忆标签，改名、补别名 | 本人 |
| 文件记忆 | 你传过的附件解析结果（就绪/失败/重试/删除） | 本人 |
| 总结 | 把流水账压成精华；立即总结/重新总结/每日自动总结 | 本人（项目总结仅项目 owner） |
| 冲突裁决 | 记忆互相矛盾时人工选留哪条 | 本人 |
| gen 矩阵 | 控制项目对话是否生成记忆（省 token） | owner 管项目闸 + 本人覆写 |
| 收录规则 | 项目级：哪些对话/文件该被项目收录 | 项目 owner/admin |
| 收录审核 | 项目记忆条目审核（收录/弃/撤回） | owner/admin 审，作者可撤回自己的 |
| 项目授权 | 把项目记忆授权给其他项目/个人/公共池 | owner/admin + 申请人 |

## 二、流水账（自动留痕，无需操作）

- 每一轮对话自动各记一行「我说 / 回答」，卡片显示时间、概要、标签。
- 被项目收录的轮次会带「**收录于：项目X**」蓝标。
- 勾选行 →「删所选」可删原文。
- 流水账**只有你自己能看见**，无需隐私设置。

## 三、标签库（让 AI 记得更准）

1. 记忆抽屉 →「标签库」→「新建」：填主体（默认「我」）、大类、名称、别名。
2. 之后聊天里说到相关话题，自动归到这个标签下。
3. 改名/补别名：点某行「编辑」（说「配偶」也能匹配上「妻子」标签）。
4. 「重新归类」：让 AI 把历史流水账里属于该标签的补挂上（只增不删）。
5. **不要**手动合并/拆分标签（不可逆，会弄乱已有总结）。

## 四、总结（把碎碎念压成精华）

1. 记忆抽屉 →「总结」→ 顶部选「个人」或你的项目。
2. **立即总结**：把最近新增的流水账压成总结。
3. **重新总结**：按标签/时间/方向强制重压。
4. 勾「加入每日自动总结」→ 每天定时自动压（没有新增时自动跳过，不花 token）。
5. 总结卡片的状态：CLEAN 正常 / STALE 源被删过会重生 / PENDING_CONFLICT 有冲突待裁决。

## 五、文件记忆（传过的附件）

1. 记忆抽屉 →「文件记忆」：看到每个附件的状态（解析中/就绪/失败）。
2. 失败的点「重试」；不需要的点「删除」（删除后文件和相关引用一并失效）。
3. 「就绪」的文件在相关问题时会以 🗂 文件卡片出现在 AI 回答里，可点下载。

## 六、gen 矩阵（不想被记忆就关）

