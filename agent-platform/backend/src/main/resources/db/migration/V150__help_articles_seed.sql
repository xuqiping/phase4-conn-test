# 知识库运维（管理员）

> 入口：「知识库」页的「索引运维」「RAG 评测」页签（仅知识库管理岗可见）。

## 一、索引重建与切换

什么时候用：换 Embedding 模型后、索引异常时。

1. 「索引运维」页签 → 选知识库 →「刷新状态」看当前快照。
2. 输新 snapshot ID → 先点「对账 / 重建预检」（不改数据）。
3. 点「启动重建」→ 页面显示进度（已完成/总数/失败数）；刷新页面进度不丢。
4. 状态到 READY → 点「切换」（二次确认）。异常可点「回滚」恢复上一快照。
5. 启动/取消/切换/回滚都会记管理员审计。

## 二、RAG 评测（改检索配置前先验证）

1. 「RAG 评测」页签 → 创建数据集（选知识库、起名）。
2. 粘贴 JSONL 评测用例（每行一个 JSON）→「导入用例」（单行错只报行号，不影响其他行）。
3. 填待测 Pipeline 版本 →「启动真实评测」→ 异步跑，可离开页面。
4. 完成后看指标：Recall@10、MRR、nDCG、引用覆盖、忠实度、拒答准确率等。

## 三、灰度发布与回滚

1. 「索引运维」→「RAG 灰度发布」区 →「刷新当前状态」。
2. 选比例（**只支持 5%/20%/50%/100%**）+ 输配置版本 →「应用灰度」→ 二次确认。
3. 系统权威检查发布门禁（评测指标达标 + 索引健康 + 对账通过），不通过会被拒——先补评测/对账。
4. 异常时点「回滚灰度」→ 恢复上一配置。

**要点**：同一用户稳定落在同一版本不漂移；灰度状态存库，后端重启不丢。

## 四、文档隔离处置

文档状态红色「已隔离」= 内容疑似提示词注入被自动隔离（不进索引）。
1. 点该文档行「解除隔离」（确认内容确实无恶意再解）。
2. 文档自动重新走解析+索引。
3. 解除后很快又被隔离 → 内容确实反复命中特征，人工核对原文，别无脑连解。
