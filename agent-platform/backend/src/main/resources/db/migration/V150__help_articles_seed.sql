3. **删连线**：单击连线（变红加粗）→ 按 Delete。
4. **快速建下一节点**：从节点右侧圆点**拉线到空白处松手** → 弹出搜索框选类型 → 回车，新节点自动建在线上。

## 四、@引用（在提示词里引用上游产出）

1. 文本/脚本/视频节点的输入框里输 **`@`** → 弹出候选列表（只列连线上游节点）。
2. 选中插入 → 生成时自动替换为上游节点的产出内容。
3. 上游被删/断连 → 显示黄色「断链引用」警告，重连或移除即可。
4. 节点重命名不影响 @引用（存的是内部编号）。

## 五、视频小工具（选中视频节点 → 属性面板）

