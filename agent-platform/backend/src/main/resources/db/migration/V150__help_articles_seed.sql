# 智能对话：聊天、联网搜索、附件

> 入口：左侧菜单「**智能对话**」。看完这篇，你能：流畅对话、让 AI 查实时信息、传文件给 AI 看。

## 一、基本对话

1. 打开「智能对话」，左侧是会话列表，可新建会话。
2. 底部输入框打字 → 发送 → AI 逐字流式回答。
3. **换模型**：输入框附近的模型下拉，选平台配置的模型。
4. **停止生成**：AI 回答太长/答偏时，点回答气泡下方的「⏹ 停止生成」——已生成的部分会保留。
5. **复制**：回答完结后，悬停气泡出现复制按钮；有「思考过程」的回答，思考和回答可**分别复制**。

> 一个会话聊太久会提示「请开通新会话继续」（安全限额）——新建会话即可，历史会话仍可回看。

## 二、联网搜索（问天气、新闻、今天几号）

1. 输入框下方工具栏找到「**🌐 联网：关**」下拉 → 选「🌐 联网：开」。
2. 正常发消息（如「今天什么日期？」「最近有什么新闻」）。
3. AI 回答里出现 `[1][2]` 编号，回答下方有「**📎 引用来源**」区。
4. 点蓝色的「🌐 标题」链接 → 新标签页打开原网页。
5. 不用了把下拉切回「关」。开关状态会记住，刷新不丢。

**注意**：
- 联网开了但没引用 = 这次没搜到内容，AI 仍会正常作答（不报错）。
- 知识库引用和联网引用可同时出现（编号不串：知识库 `[n]`，联网 `🌐[n]`）。
- 若怎么开都没引用 → 管理员可能没开后台总开关，找管理员。

## 三、传附件给 AI（文件记忆）

1. 输入框点 **📎** 上传附件（PDF/PPT/Word/图片/音频/视频）。
2. 附件显示「解析中」→ 稍等变「**就绪**」（AI 已读懂文件内容）。
3. 直接提问，AI 会优先参考这个附件回答，回答顶部有「📎 本附件」卡片。
4. 之后相关问题也可能自动带出这个文件（🗂 文件卡片，可点下载）。

**注意**：
- 附件还在「解析中」时提问，AI 不会读到它的内容——等变「就绪」再问。
- 记忆总开关关掉时，附件注入同样不生效。
- 文件名命中你项目收录规则的（如「周报-xx.docx」），AI 会先问一句「已被项目收录，需要我回答吗？」——点「需要回答」才正式作答，这是防误录设计。

## 四、对话花积分

聊天按所选模型和实际用量自动扣积分，失败的调用自动全额退款。余额明细见「我的钱包」。余额不足时会提示，充值后即可继续。
