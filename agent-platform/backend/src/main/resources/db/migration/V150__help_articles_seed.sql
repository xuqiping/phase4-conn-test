# 登录、注册与找回密码

> 看完这篇，你能：注册账号、用三种方式登录、忘记密码时自己找回。

## 一、注册新账号

1. 打开平台登录页，点「**注册账号**」（或「立即注册」）。
2. 填写：**用户名 + 邮箱 + 密码 + 确认密码**。
   - 密码要求：6 位以上，**同时包含大写字母、小写字母、数字、特殊符号**（如 `Str0ng#Pass`）。
   - `123456`、`admin123` 这类常见密码会被拒绝；密码不能和用户名一样。
3. 勾选「我已阅读并同意《用户协议》」（不勾选注册按钮是灰的）。
4. 点「**注册**」→ 提示注册成功。
5. 如果平台开启了邮箱验证：注册前去邮箱收一封「注册验证码」邮件，把 6 位数字填进「邮箱验证码」再提交（验证码 10 分钟内有效）。

> 注册成功后即可登录。邮箱验证不是登录的前提，但**未验证的邮箱不能用来找回密码**。

## 二、登录（三种方式）

### 方式 1：账号密码登录（默认）
1. 登录页默认就在「账号密码」页签。
2. 输入用户名 + 密码 → 点「登录」→ 进入首页。
3. 连续输错几次后会出现**滑块拼图**：拖动滑块对准缺口，再点登录（这是防机器人，正常操作即可）。

### 方式 2：手机验证码登录
1. 切到「手机验证码」页签。
2. 输入 11 位手机号 → 点「获取验证码」（可能需要先过滑块）。
3. 手机收到 6 位验证码 → 填入 → 点「登录」。
4. **新手机号会自动注册并直接登录**，不用单独注册。

> 60 秒内只能发一次验证码；验证码错 5 次就作废，需重新获取。

### 方式 3：扫码登录
1. 切到「扫码登录」页签（看不到这个页签 = 管理员没开启，用前两种方式）。
2. 按提示用微信/钉钉扫码，手机上点确认 → 自动登录进首页。

## 三、忘记密码怎么办

1. 登录页点「**忘记密码**」。
2. 选「邮箱」或「短信」渠道 → 输入你的账号 → 点「发送」。
   - 无论账号是否存在，页面都提示「若账号存在，重置链接已发送」（防别人探测账号，属正常）。
3. 收邮件（点邮件里的重置按钮）或收短信验证码。
4. 在打开的页面输入**新密码** → 确认。
5. 提示成功后用新密码登录。**所有旧设备会被自动踢下线**（安全设计）。

> 收不到重置邮件？说明该邮箱没验证过：先登录 → 右上角头像 → 设置 → 安全设置 → 绑定并验证邮箱。

## 四、登录后会被踢下线的情况

| 情况 | 原因 | 怎么办 |
|---|---|---|
| 提示「账号已在别处登录」 | 同账号只允许一处在线，你在别的设备登录了 | 是本人操作：重新登录即可；不是本人：立刻改密码 |
| 改了密码后被踢出 | 改密码会踢掉所有设备（安全设计） | 用新密码重新登录 |
| 提示「登录失败次数过多」 | 密码连错 5 次，账号锁 15 分钟 | 等 15 分钟自动解锁；急用找管理员 |
| 页面开着突然被要求重新登录 | 超过 7 天没活动，或账号被管理员封禁 | 重新登录；被封找管理员 |

## 五、绑定/解绑登录方式（设置 → 安全设置）

- 登录后点右上角头像 → 「设置」→「安全」标签页，能看到你当前的所有登录方式（密码/邮箱/手机/微信）。
- **绑定邮箱**：点「+ 绑定邮箱」→ 输邮箱 → 去邮箱点激活链接 → 列表变「已验证」。
- **解绑**：点某条凭证的「解绑」。注意：**密码不能解绑**；只剩一种登录方式时也不让解绑（防止把自己锁死）。
- **修改密码**：在「修改密码」卡片输当前密码 + 新密码 → 改完自动退出，用新密码重登。
