## 一、全局模型供应商

**新增供应商**：按类别建——CHAT（对话）/ IMAGE（图片）/ MEDIA（视频）/ EMBEDDING（向量）/ RERANK（重排）。填名称、类别、接口地址、API Key、模型列表。

