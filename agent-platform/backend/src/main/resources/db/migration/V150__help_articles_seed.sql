# 账号安全须知

> 平台有安全护栏，平时无感；撞到规则时对照这篇处理。

## 一、登录被锁了

| 提示 | 发生了什么 | 怎么办 |
|---|---|---|
| 「登录失败次数过多」 | 你的账号密码连错 5 次，锁定 15 分钟（正确密码也进不去） | 等 15 分钟自动解锁；不是本人试的→解锁后立刻改密码 |
| 同 IP 被封 1 小时 | 同一网络一小时失败超 20 次（公司共用网络可能被同事连累） | 等自动解封，或找管理员 |

## 二、提示「账号已在别处登录」

同账号**只允许一处在线**：你在别的设备/浏览器登录，这边就被踢下线。

- 是本人换设备 → 正常现象，重新登录即可。
- **不是本人** → 立即改密码，并联系管理员查登录记录。

> 页面开着不用重新登录：凭证每 15 分钟自动静默续期，只有长期未活动/被踢/被封才会跳登录页。

## 三、两步验证（TOTP，管理员建议开）

绑定后登录要「密码 + 手机 6 位动态码」两道，账号更安全。

**绑定步骤**（设置 → 安全设置 → TOTP 两步验证）：
1. 点「开始绑定」→ 页面显示密钥和二维码。
2. 手机装验证器 App（Google/Microsoft Authenticator 等）→ 扫码或手动输密钥。
3. 输入 App 里当前的 6 位码确认 → 绑定成功。
4. **立即抄写保存 8 组恢复码**（只显示这一次！手机丢了靠它登录）。

**解绑**：TOTP 卡片点「解绑」，需输一个当前有效的 6 位码。

**常见问题**：验证码总报错 → 检查手机时间是否自动同步（时间差大码就全错）；手机丢了 → 用恢复码登录后重新绑定。

## 四、上传文件被拒绝了

| 提示 | 原因 | 怎么办 |
|---|---|---|
| 「文件类型不允许上传」 | 传了 .html/.svg/.exe/.js 等危险类型 | 文档/图片/音视频/pdf 都能传；代码打包成 .zip 再传 |
| 「文件内容与声明类型不符」 | 文件被改过扩展名（如 exe 改名 png） | 改回真实后缀再传 |
| 「图片分辨率过大」 | 图片总像素超 1 亿 | 缩小后再传（正常照片远达不到） |
| 「存储空间已满」 | 个人存储配额（默认 2GB）用满 | 删除旧文件释放额度，或找管理员调大 |
| 「操作过于频繁」 | 上传每分钟限 10 次 | 等 1 分钟再继续 |

## 五、使用中的其他限制（属正常安全设计）

- **发消息太快**被限：对话每分钟限 20 条，等 1 分钟恢复。
- **单会话用量到顶**：一个会话聊太久会提示开新会话（历史记录仍可看）。
- **AI 回复里出现 `***`**：身份证号/手机号等敏感信息被自动打码，属正常。
- **余额低时不能并行**：积分余额低于阈值时同时只能跑 1 个任务，等当前任务跑完再发下一条；充值后立即恢复。

## 六、注销账号（不可恢复！）

入口：设置 → 安全设置 → 最底部「注销账号」。

1. 点「注销我的账号」→ 看清警示。
2. 输入**当前密码** + 手动输入「注销」两个字 → 确认。

**注销前务必知道**：
- 用户名/邮箱/手机号**永久清除，无法恢复**；余额**不退**，先花完或放弃。
- 计费流水和审计日志按法规脱敏保留（不再关联你本人）。
- 所有设备立刻被踢下线，原账号无法再登录。
