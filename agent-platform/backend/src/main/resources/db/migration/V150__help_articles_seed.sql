- 行内「测试」：Embedding 成功显示维度；Rerank 成功显示排序正确。
- ⚠️ 配完模型还要去「价表配置」定价，否则调用无法计费。

**导出/导入**（备份/迁移）：
1. 「导出」→ 确认窗提示「含明文 API Key」→ 下载 JSON。⚠️ 文件含明文密钥，别发群/别提交 git。
