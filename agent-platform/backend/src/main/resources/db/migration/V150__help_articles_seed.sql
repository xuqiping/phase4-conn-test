Grafana「告警」→「静默」→ 新建静默 → 匹配器选告警名 + 填时长 → 期间该告警不发钉钉，到期自动恢复。

## 五、发布新版本

1. 开发机构建出 jar 和 dist，拷到服务器。
2. 管理员 cmd 跑 `deploy.bat D:\pkg\xxx.jar D:\pkg\dist` → 窗口显示 1/5~5/5 →「发布完成」。
3. 显示「自动回滚」= 发布失败旧版已恢复，钉钉会收告警，查日志找原因。

